/** প্রোডাক্টের বাস্তব তথ্য — মডেলের "রিসার্চ মেটেরিয়াল" */
function researchBrief(product: Product, page: Page): string {
  const highlights = product.features.map((feature, index) => {
    const label = product.enrich?.featureLabels?.[index];
    return label && !feature.startsWith(label) ? `- ${label}: ${feature}` : `- ${feature}`;
  });

  return `পণ্য: ${product.nameBn}
ইংরেজি নাম: ${product.enrich?.nameEn ?? product.nameBn}
ক্যাটাগরি: ${product.category}
দাম: ${taka(product.priceBdt)}${product.compareAtPriceBdt ? ` (আগে ${taka(product.compareAtPriceBdt)})` : ""}
স্টক: ${bnNumber(product.stock)}
অফার: ${product.offerText ?? "নেই"}
মেটেরিয়াল: ${product.material ?? "উল্লেখ নেই"}
কাদের জন্য: ${product.targetAudience ?? "উল্লেখ নেই"}
পণ্যের দাবি করা সমস্যা: ${product.problemBn}
পণ্যের দাবি করা সমাধান: ${product.solutionBn}
ফিচার (লেবেল — মূল বর্ণনা):
${highlights.join("\n") || "- উল্লেখ নেই"}
ব্র্যান্ড: ${page.brandName} — ${page.tagline}`;
}

